export async function exportSalesReportPDF(payload: ExportPayload) {
  const logoDataUri = await getBrandLogoDataUri();
  const html = buildReportHtml(payload, logoDataUri);
  const file = await Print.printToFileAsync({ html });

  await shareFile(file.uri, 'application/pdf', 'Export Sales Report (PDF)');
}
