import { Asset } from 'expo-asset';
import * as FileSystem from 'expo-file-system/legacy';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import * as XLSX from 'xlsx';

import { CategorySales, Order, SalesMetrics } from '../types/models';
import { formatDateTime } from '../utils/date';

interface ExportPayload {
  rangeLabel: string;
  generatedBy: string;
  metrics: SalesMetrics;
  categorySales: CategorySales[];
  transactions: Order[];
}

const BRAND_LOGO = require('../../assets/suki-send-logo.png');

function buildTimestamp() {
  const now = new Date();
  return `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, '0')}${String(now.getDate()).padStart(2, '0')}-${String(
    now.getHours(),
  ).padStart(2, '0')}${String(now.getMinutes()).padStart(2, '0')}`;
}

function escapeHtml(value: string) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

async function shareFile(uri: string, mimeType: string, dialogTitle: string) {
  const canShare = await Sharing.isAvailableAsync();
  if (!canShare) {
    throw new Error('File sharing is not available on this device.');
  }

  await Sharing.shareAsync(uri, {
    mimeType,
    dialogTitle,
  });
}

async function getBrandLogoDataUri() {
  try {
    const asset = Asset.fromModule(BRAND_LOGO);
    if (!asset.localUri) {
      await asset.downloadAsync();
    }

    const sourceUri = asset.localUri ?? asset.uri;
    if (!sourceUri) {
      return null;
    }

    const base64 = await FileSystem.readAsStringAsync(sourceUri, {
      encoding: FileSystem.EncodingType.Base64,
    });
    return `data:image/png;base64,${base64}`;
  } catch {
    return null;
  }
}

function buildWorkbook(payload: ExportPayload) {
  const workbook = XLSX.utils.book_new();

  const summaryRows: Array<Array<string | number>> = [
    ['SUKI SEND'],
    ['From Store to Door, Ka Suki'],
    ['Brand Logo Asset', 'suki-send-logo.png'],
    [],
    ['Range', payload.rangeLabel],
    ['Generated By', payload.generatedBy],
    ['Generated At', new Date().toLocaleString()],
    [],
    ['Gross Sales', payload.metrics.grossSales],
    ['Profit', payload.metrics.profit],
    ['Paid Orders', payload.metrics.totalOrders],
    ['Average Order Value', payload.metrics.averageOrderValue],
    ['Top Selling Product', payload.metrics.topSellingProduct],
    ['Low Stock Items', payload.metrics.lowStockCount],
  ];
  const summarySheet = XLSX.utils.aoa_to_sheet(summaryRows);
  summarySheet['!cols'] = [{ wch: 28 }, { wch: 32 }];
  XLSX.utils.book_append_sheet(workbook, summarySheet, 'Summary');

  const categoryRows = payload.categorySales.length
    ? payload.categorySales.map((entry) => [entry.category, entry.sales])
    : [['No category sales data', 0]];
  const categorySheet = XLSX.utils.aoa_to_sheet([
    ['Category', 'Sales'],
    ...categoryRows,
  ]);
  categorySheet['!cols'] = [{ wch: 28 }, { wch: 16 }];
  XLSX.utils.book_append_sheet(workbook, categorySheet, 'Category Sales');

  const transactionRows = payload.transactions.length
    ? payload.transactions.map((order) => [
        order.orderNo,
        formatDateTime(order.createdAt),
        order.status,
        order.deliveryArea,
        order.total,
      ])
    : [['No paid transactions found', '', '', '', 0]];
  const transactionsSheet = XLSX.utils.aoa_to_sheet([
    ['Order No', 'Date', 'Status', 'Delivery Area', 'Total'],
    ...transactionRows,
  ]);
  transactionsSheet['!cols'] = [{ wch: 16 }, { wch: 22 }, { wch: 16 }, { wch: 28 }, { wch: 14 }];
  XLSX.utils.book_append_sheet(workbook, transactionsSheet, 'Transactions');

  return workbook;
}

export async function exportSalesReportXLSX(payload: ExportPayload) {
  const timestamp = buildTimestamp();
  const fileUri = `${FileSystem.documentDirectory}suki-send-sales-${timestamp}.xlsx`;
  const workbook = buildWorkbook(payload);
  const contentBase64 = XLSX.write(workbook, { bookType: 'xlsx', type: 'base64' });

  await FileSystem.writeAsStringAsync(fileUri, contentBase64, {
    encoding: FileSystem.EncodingType.Base64,
  });

  await shareFile(
    fileUri,
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    'Export Sales Report (Excel/XLSX)',
  );
}

export const exportSalesReportCSV = exportSalesReportXLSX;

